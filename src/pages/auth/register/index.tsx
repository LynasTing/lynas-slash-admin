import { Form, FormField, FormItem, FormControl, FormMessage } from '@/ui/form';
import { Input } from '@/ui/input';
import Button from '@/ui/button';
import { useForm } from 'react-hook-form';
import { useTranslation } from 'react-i18next';
import { useMutation } from '@tanstack/react-query';
import { useNavigate } from 'react-router';
import { toast } from 'sonner';
import { registerApi } from '@/api/auth';
import type { TFunction } from 'i18next';
import { z } from 'zod';
import type { RegisterRequest } from '#/auth';
import { zodResolver } from '@hookform/resolvers/zod';
import { useMemo, useState } from 'react';
import { Icon } from '@/components/icon';
import { LoginStateEnum, useLoginStateContext } from '../providers/declaration';

/**
 * 创建注册表单校验规则，校验消息通过翻译函数生成
 * Create registration form validation rules with messages generated by the translation function
 */
const createSignUpFormSchema = (t: TFunction) =>
  z
    .object({
      username: z.string().trim().min(2, t('auth.validation.usernameMinLength')).max(64, t('auth.validation.usernameMaxLength')),
      nickname: z
        .string()
        .trim()
        .refine(value => value === '' || value.length >= 2, t('auth.validation.nicknameMinLength'))
        .refine(value => value === '' || value.length <= 64, t('auth.validation.nicknameMaxLength')),
      email: z
        .string()
        .trim()
        .min(1, t('auth.validation.emailRequired'))
        .email(t('auth.validation.emailInvalid'))
        .max(255, t('auth.validation.emailMaxLength')),
      password: z
        .string()
        .min(1, t('auth.validation.passwordRequired'))
        .min(8, t('auth.validation.passwordMinLength'))
        .max(72, t('auth.validation.passwordMaxLength'))
        .refine(value => value.trim().length > 0, t('auth.validation.passwordRequired')),
      confirmPassword: z.string().min(1, t('auth.validation.confirmPasswordRequired'))
    })
    .superRefine((values, context) => {
      // 将跨字段错误绑定到确认密码字段，让 FormMessage 在对应输入框下方显示
      // Attach the cross-field error to confirmPassword so FormMessage renders it under the matching input
      if (values.password !== values.confirmPassword) {
        context.addIssue({
          code: 'custom',
          path: ['confirmPassword'],
          message: t('auth.validation.passwordMismatch')
        });
      }
    });

/**
 * 从注册表单 Schema 推导表单值类型
 * Infer the form value type from the registration form schema
 */
type SignUpFormValues = z.infer<ReturnType<typeof createSignUpFormSchema>>;

function Register() {
  const { t } = useTranslation();
  const navigate = useNavigate();
  const signUpFormSchema = useMemo(() => createSignUpFormSchema(t), [t]);
  const [showPwd, setShowPwd] = useState(false);
  const [showConfirmPwd, setShowConfirmPwd] = useState(false);
  const { loginState, setLoginState } = useLoginStateContext();

  /**
   * 表单默认值包含仅供前端确认密码的字段，不会直接发送到后端
   * Default values include the frontend-only confirmation field, which is never sent directly to the backend
   */
  const defaultValues: SignUpFormValues = {
    username: '',
    nickname: '',
    email: '',
    password: '',
    confirmPassword: ''
  };

  /**
   * 使用 zodResolver 将 Schema 错误转换为 React Hook Form 字段错误，避免维护两套校验规则
   * Use zodResolver to convert schema errors into React Hook Form field errors and avoid two validation systems
   */
  const form = useForm<SignUpFormValues>({
    resolver: zodResolver(signUpFormSchema),
    defaultValues,
    mode: 'onBlur',
    reValidateMode: 'onChange'
  });

  const signUpMutation = useMutation({
    mutationFn: registerApi
  });

  if (loginState !== LoginStateEnum.REGISTER) {
    return null;
  }

  /**
   * 提交通过校验的表单，并显式转换为后端请求参数，排除 confirmPassword
   * Submit validated form data by explicitly converting it to the backend request and excluding confirmPassword
   */
  const onFinish = async (values: SignUpFormValues) => {
    const request: RegisterRequest = {
      username: values.username,
      email: values.email,
      password: values.password
    };

    // 可选昵称只有在填写后才加入请求，避免把空字符串发送给后端校验
    // Add the optional nickname only when provided to avoid sending an empty string to backend validation
    if (values.nickname) {
      request.nickname = values.nickname;
    }

    try {
      await signUpMutation.mutateAsync(request);
      toast.success(t('auth.registerSuccess'), {
        position: 'top-center'
      });
      setTimeout(() => {
        setLoginState(LoginStateEnum.LOGIN);
        navigate('/auth/login', { replace: true });
      }, 1500);
    } catch (error) {
      // 请求错误属于服务端或网络错误，不应伪装成表单字段校验错误
      // Request failures are server or network errors and should not be presented as field validation errors
      const message = error instanceof Error ? error.message : t('sys.api.errorMessage');
      toast.error(message, {
        position: 'top-center'
      });
    }
  };
  return (
    <Form {...form}>
      <form className="space-y-4" onSubmit={form.handleSubmit(onFinish)}>
        <div className="flex flex-col items-center gap-2 text-center">
          <h1 className="text-2xl font-bold">{t('auth.signUpFormTitle')}</h1>
        </div>
        <FormField
          control={form.control}
          name="username"
          render={({ field }) => (
            <FormItem>
              <FormControl>
                <Input placeholder={t('auth.usernamePlaceholder')} {...field} />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="nickname"
          render={({ field }) => (
            <FormItem>
              <FormControl>
                <Input placeholder={t('auth.nicknamePlaceholder')} {...field} />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="email"
          render={({ field }) => (
            <FormItem>
              <FormControl>
                <Input type="email" placeholder={t('auth.emailPlaceholder')} {...field} />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="password"
          render={({ field }) => (
            <FormItem>
              <div className="flex items-center">
                <FormControl>
                  <Input type={showPwd ? 'text' : 'password'} placeholder={t('auth.passwordPlaceholder')} {...field} />
                </FormControl>
                <Button type="button" variant="link" className="text-gray-600" onClick={() => setShowPwd(() => !showPwd)}>
                  <Icon icon={showPwd ? 'mdi:eye-off' : 'mdi:eye'} size={14} />
                </Button>
              </div>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="confirmPassword"
          render={({ field }) => (
            <FormItem>
              <div className="flex">
                <FormControl>
                  <Input type={showConfirmPwd ? 'text' : 'password'} placeholder={t('auth.confirmPasswordPlaceholder')} {...field} />
                </FormControl>
                <Button type="button" variant="link" className="text-gray-600" onClick={() => setShowConfirmPwd(() => !showConfirmPwd)}>
                  <Icon icon={showConfirmPwd ? 'mdi:eye-off' : 'mdi:eye'} size={14} />
                </Button>
              </div>
              <FormMessage />
            </FormItem>
          )}
        />
        <Button type="submit" className="w-full" disabled={signUpMutation.isPending}>
          {t('auth.registerButton')}
        </Button>
        <div className="text-gray mb-2 text-xs">
          <span>{t('auth.registerAndAgree')}</span>
          <a href="javascript:void(0)" className="text-sm text-primary! underline!">
            {t('auth.termsOfService')}
          </a>
          {' & '}
          <a href="javascript:void(0)" className="text-sm text-primary! underline!">
            {t('auth.privacyPolicy')}
          </a>
        </div>
      </form>
    </Form>
  );
}

export default Register;
